"""Focused regression tests for generated preview-file formats."""

from __future__ import annotations

import tempfile
import unittest
from pathlib import Path

from app.services.drama.image_preview_files import (
    detect_preview_extension,
    repair_cached_preview_pair,
    write_preview_pair,
)


class ImagePreviewFilesTests(unittest.TestCase):
    def test_detect_preview_extension_uses_image_signature(self):
        """Choose PNG and JPEG suffixes from their respective signatures."""
        with tempfile.TemporaryDirectory() as temp_dir:
            root = Path(temp_dir)
            png = root / "preview.png"
            jpeg = root / "preview.jpg"
            png.write_bytes(b"\x89PNG\r\n\x1a\ncontent")
            jpeg.write_bytes(b"\xff\xd8\xffcontent")

            self.assertEqual(detect_preview_extension(png), ".png")
            self.assertEqual(detect_preview_extension(jpeg), ".jpg")

    def test_write_preview_pair_uses_one_matching_extension_and_removes_stale_names(
        self,
    ):
        """Mirror generated bytes with one matching name in both roots."""
        with tempfile.TemporaryDirectory() as temp_dir:
            root = Path(temp_dir)
            source = root / "generated.png"
            source.write_bytes(b"\x89PNG\r\n\x1a\nimage-data")
            backend_dir = root / "backend"
            frontend_dir = root / "frontend"
            backend_dir.mkdir()
            frontend_dir.mkdir()
            (backend_dir / "style.jpg").write_bytes(b"stale")
            (frontend_dir / "style.jpg").write_bytes(b"stale")

            extension = write_preview_pair(
                source, "style", backend_dir, frontend_dir
            )

            self.assertEqual(extension, ".png")
            self.assertEqual(
                (backend_dir / "style.png").read_bytes(), source.read_bytes()
            )
            self.assertEqual(
                (frontend_dir / "style.png").read_bytes(), source.read_bytes()
            )
            self.assertFalse((backend_dir / "style.jpg").exists())
            self.assertFalse((frontend_dir / "style.jpg").exists())

    def test_repair_cached_preview_rehomes_misnamed_file_without_regenerating(
        self,
    ):
        """Repair a cached JPEG named PNG without requesting a new image."""
        with tempfile.TemporaryDirectory() as temp_dir:
            root = Path(temp_dir)
            backend_dir = root / "backend"
            frontend_dir = root / "frontend"
            backend_dir.mkdir()
            frontend_dir.mkdir()
            actual_jpeg = b"\xff\xd8\xff" + (b"jpeg-content" * 1_000)
            (backend_dir / "style.png").write_bytes(actual_jpeg)
            (frontend_dir / "style.png").write_bytes(b"stale frontend copy")

            extension = repair_cached_preview_pair(
                "style", backend_dir, frontend_dir
            )

            self.assertEqual(extension, ".jpg")
            self.assertEqual(
                (backend_dir / "style.jpg").read_bytes(), actual_jpeg
            )
            self.assertEqual(
                (frontend_dir / "style.jpg").read_bytes(), actual_jpeg
            )
            self.assertFalse((backend_dir / "style.png").exists())
            self.assertFalse((frontend_dir / "style.png").exists())

    def test_unsupported_image_format_is_rejected(self):
        """Fail closed when bytes are not one of the served image formats."""
        with tempfile.TemporaryDirectory() as temp_dir:
            image = Path(temp_dir) / "preview.bin"
            image.write_bytes(b"not an image")
            with self.assertRaises(ValueError):
                detect_preview_extension(image)


if __name__ == "__main__":
    unittest.main()
