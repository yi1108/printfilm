/** Resolve current UI locale at call time and interpolate values without translating them. */
export function studioSecondaryText(source: string, values: unknown[] = [], locale: Locale = getActiveLocale()): string {
  const template = locale === 'en' ? studioSecondaryEnglish[source] || source : source
  return template.replace(/\{(\d+)\}/g, (match, index: string) => Number(index) < values.length ? String(values[Number(index)] ?? '') : match)
}
